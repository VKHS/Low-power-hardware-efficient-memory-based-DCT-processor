# ---------------------------------------------------------------- committed data belongs to this tree
def test_evidence_was_generated_from_the_current_sources():
    now = evidence.source_digest(ROOT)
    assert EVIDENCE["meta"]["source"] == now, (
        "python/dct8/*.py or vectors/* changed: run `python scripts/make_artifact.py`")


def test_recorded_vector_digests_match_the_files():
    for name, entry in EVIDENCE["vectors"]["sets"].items():
        for suffix, f in entry["files"].items():
            data = (ROOT / "vectors" / f"{name}_{suffix}").read_bytes()
            assert evidence._sha(data) == f["sha256"], (name, suffix)
            assert len(data) == f["bytes"]
    for name, f in EVIDENCE["vectors"]["files"].items():
        assert evidence._sha((ROOT / "vectors" / name).read_bytes()) == f["sha256"]


def _embedded(page, ident):
    m = re.search(r'<script type="application/json" id="%s">(.*?)</script>' % ident, page, re.S)
    assert m, ident
    return json.loads(m.group(1))


def test_page_embeds_the_committed_data():
    page = (ROOT / "artifact" / "index.html").read_text(encoding="utf-8")
    assert _embedded(page, "evidence") == EVIDENCE
    vec = _embedded(page, "vectors")
    manifest = json.loads((ROOT / "vectors" / "manifest.json").read_text())
    assert json.loads(vec["manifest.json"]) == manifest
    assert vec["schedule.json"] == (ROOT / "vectors" / "schedule.json").read_text()
    for name in manifest:
        for key, suffix in (("in", "in.txt"), ("out", "out.txt"), ("stim", "stim.hex"), ("expect", "expect.hex")):
            assert vec["sets"][name][key] == (ROOT / "vectors" / f"{name}_{suffix}").read_text(), (name, key)


