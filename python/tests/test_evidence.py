# ---------------------------------------------------------------- the report and the page agree
def _md():
    return (ROOT / "docs" / "results.md").read_text()


def test_one_dimensional_rows_are_in_the_report():
    md, rows = _md(), EVIDENCE["accuracy_1d"]["rows"]
    for w in range(8, 17):
        a = next(r for r in rows if r["mode"] == "table1" and r["w"] == w and r["best"])
        b = next(r for r in rows if r["mode"] == "cordic2x" and r["w"] == w and r["best"])
        line = (f"| {w} | {''.join(map(str, a['ss']))} | {a['sqnr']:.2f} | {a['rms']:.4f} | "
                f"{b['sqnr']:.2f} | {b['rms']:.4f} | {a['sqnr_exact_rot']:.2f} |")
        assert line in md, line


def test_two_dimensional_and_zonal_rows_are_in_the_report():
    md, d = _md(), EVIDENCE
    for w in range(8, 17):
        cells = []
        for mode in ("table1", "cordic2x"):
            r = next(q for q in d["accuracy_2d"]["rows"] if q["w"] == w and q["mode"] == mode)
            cells.append(f"{r['mean']:.2f} ({r['min']:.1f} - {r['max']:.1f})")
        assert f"| {w} | {cells[0]} | {cells[1]} |" in md
    for img in d["accuracy_2d"]["images"]:
        vals = [r["psnr_hw"] for r in d["compression"]["rows"] if r["image"] == img]
        assert f"| {img} | " + " | ".join(f"{v:.2f}" for v in vals) + " |" in md
    assert f"{d['compression']['max_abs_diff_db']:.4f} dB" in md


def test_cost_and_rotation_rows_are_in_the_report():
    md, d = _md(), EVIDENCE
    for r in d["cost"]["rows"]:
        if r["w"] in (10, 14):
            assert (f"| W={r['w']}, G=3, {r['mode']} | {r['adders']} | {r['adder_bits']} | "
                    f"{r['rounding_increments']} | {r['register_bits']} | {r['memory_words']} | 0 |") in md
    for mode in ("table1", "cordic2x"):
        for r in d["rotations"][mode]:
            assert (f"| {mode} | {r['k']} | {r['target_deg']:.4f}° | {r['realised_deg']:.4f}° | "
                    f"{r['angle_err_rad']:+.2e} | {r['gain']:.6f} |") in md


