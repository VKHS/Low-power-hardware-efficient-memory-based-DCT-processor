"""The numbers on the results page: second-route checks, negative controls and freshness.

``artifact/data/evidence.json`` is generated by ``python scripts/make_artifact.py``.  These tests
re-derive what is cheap to re-derive and confirm that the committed data belongs to the current
sources.
"""
