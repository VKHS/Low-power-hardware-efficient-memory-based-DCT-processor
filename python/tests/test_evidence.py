# ---------------------------------------------------------------- the build script
def _load_build_script():
    spec = importlib.util.spec_from_file_location("make_artifact", ROOT / "scripts" / "make_artifact.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


MA = _load_build_script()


def test_check_tolerates_float_noise_only():
    a = {"x": 1.0, "y": [1, 2.5], "s": "t", "b": True, "meta": {"environment": {"numpy": "1"}, "v": 3}}
    noisy = {"x": 1.0 + 1e-7, "y": [1, 2.5 + 1e-5], "s": "t", "b": True,
             "meta": {"environment": {"numpy": "2"}, "v": 3}}
    assert MA.diff(a, noisy) == []
    for path, b in [("/x", {**a, "x": 1.01}), ("/y[0]", {**a, "y": [2, 2.5]}), ("/s", {**a, "s": "u"}),
                    ("/b", {**a, "b": False}), ("/y", {**a, "y": [1]}), ("/z", {**a, "z": 1}),
                    ("/meta/v", {**a, "meta": {"v": 4}})]:
        found = MA.diff(a, b)
        assert found and found[0].startswith(path), (path, found)
    assert MA.diff({"environment": 1}, {"environment": 2}), "only meta.environment is ignored"


GOOD_FPGA = {"device": "synthetic", "tool": "synthetic", "config": "synthetic", "wl": 14, "lut": 1,
             "ff": 2, "dsp": 0, "fmax_mhz": 100.5, "power_mw": 90}


def test_measured_fpga_figures_are_validated(tmp_path):
    assert MA.fpga_measured(tmp_path / "absent.json") is None
    ok = tmp_path / "ok.json"
    ok.write_text(json.dumps({**GOOD_FPGA, "_how_to_fill": ["ignored"]}))
    assert MA.fpga_measured(ok) == GOOD_FPGA
    for key, bad in [("device", ""), ("tool", None), ("config", 3), ("wl", "14"), ("lut", None), ("ff", -1),
                     ("dsp", True), ("dsp", 1.5), ("fmax_mhz", None), ("fmax_mhz", 0), ("power_mw", "91")]:
        f = tmp_path / "bad.json"
        f.write_text(json.dumps({**GOOD_FPGA, key: bad}))
        with pytest.raises(SystemExit):
            MA.fpga_measured(f)
    f = tmp_path / "missing.json"
    f.write_text(json.dumps({k: v for k, v in GOOD_FPGA.items() if k != "power_mw"}))
    with pytest.raises(SystemExit):
        MA.fpga_measured(f)


def test_unfilled_template_cannot_reach_the_page():
    template = ROOT / "artifact" / "data" / "fpga_measured.template.json"
