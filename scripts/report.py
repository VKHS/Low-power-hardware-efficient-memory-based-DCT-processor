#!/usr/bin/env python3
"""Print the measured results of the models as Markdown (python3 scripts/report.py > docs/results.md)."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))

import numpy as np  # noqa: E402

from dct8 import analysis as A  # noqa: E402
from dct8 import cordic2, cost, processor, scalable, schedule  # noqa: E402
from dct8.processor import Config  # noqa: E402


def main() -> None:
    print("# Measured results\n")
    print("Generated by `python3 scripts/report.py` from the bit-accurate models (which the RTL, "
          "HLS and MATLAB implementations reproduce bit for bit).  Inputs: 8-bit signed samples; "
          "images: the eight grayscale test images shipped with scikit-image "
          f"({', '.join(A.test_images().keys())}).\n")

    print("## Micro-rotations of the central CORDIC unit\n")
    print("| mode | k | target | realised | angle error (rad) | gain |")
    print("|---|---|---|---|---|---|")
    for mode in cordic2.MODES:
        for r in cordic2.analyze(mode):
            print(f"| {mode} | {r.k} | {r.target_deg:.4f}° | {r.realised_deg:.4f}° | "
                  f"{r.angle_err_rad:+.2e} | {r.gain:.6f} |")
    print("\n16-point CORDIC array (paper, Table 5):\n")
    print("| k | target | P_k | realised | angle error (rad) | gain with K_k |")
    print("|---|---|---|---|---|---|")
    for r in scalable.table5_report():
        print(f"| {r['k']} | {r['target_deg']:.4f}° | {r['P']} | {r['realised_deg']:.4f}° | "
              f"{r['angle_err_rad']:+.2e} | {r['gain']:.6f} |")

    x = A.random_inputs(20000)
    print("\n## 1-D processor: accuracy versus word length\n")
    print("Best safe-scaling option per word length; 20 000 random 8-bit vectors; errors in units "
          "of the orthonormal DCT.\n")
    print("| W | SS | SQNR table1 (dB) | rms table1 | SQNR cordic2x (dB) | rms cordic2x | "
          "SQNR exact rotations (dB) |")
    print("|---|---|---|---|---|---|---|")
    rows = A.wl_sweep_1d(range(8, 17), x)
    for w in range(8, 17):
        a = [r for r in rows if r["w"] == w and r["mode"] == "table1"][0]
        b = [r for r in rows if r["w"] == w and r["mode"] == "cordic2x"][0]
        print(f"| {w} | {''.join(map(str, a['ss']))} | {a['sqnr']:.2f} | {a['rms']:.4f} | "
              f"{b['sqnr']:.2f} | {b['rms']:.4f} | {a['sqnr_ideal_rot']:.2f} |")

    print("\n## 2-D processor: PSNR against the IEEE-754 double-precision 2-D DCT\n")
    print("Both passes use word length W (row pass: best SS, column pass: SS 111); peak 255; "
          "mean (min - max) over the test images.\n")
    print("| W | table1 (dB) | cordic2x (dB) | paper, Table 3 (BSD-100, as reported) |")
    print("|---|---|---|---|")
    imgs = A.test_images()
    rows2 = A.wl_sweep_2d(range(8, 17), imgs)
    paper = {16: 56.51, 14: 43.24, 12: 32.60, 10: 17.01, 8: 6.02}
    for w in range(8, 17):
        cells = []
        for mode in cordic2.MODES:
            r = [q for q in rows2 if q["w"] == w and q["mode"] == mode][0]
            v = list(r["per_image"].values())
            cells.append(f"{r['mean']:.2f} ({min(v):.1f} - {max(v):.1f})")
        print(f"| {w} | {cells[0]} | {cells[1]} | {paper.get(w, '')} |")

    print("\n## Zonal compression (64:10, 64:6, 64:3, 64:1)\n")
    row, col = Config(8, 14, 3, (0, 0, 0), "table1"), Config(14, 16, 3, (1, 1, 1), "table1")
    table, diff = [], 0.0
    for n, im in imgs.items():
        vals = []
        for k in (10, 6, 3, 1):
            v = A.psnr(im, A.reconstruct(im, row, col, keep=k))
            diff = max(diff, abs(v - A.psnr(im, A.reconstruct(im, keep=k))))
            vals.append(v)
        table.append((n, vals))
    print("Bit-accurate 2-D processor (row W 14, column W 16, table1) -> keep the first K zig-zag "
          "coefficients -> double IDCT; PSNR against the original 8-bit image.  Largest difference "
          f"to the double-precision DCT over all images and ratios: {diff:.4f} dB.\n")
    print("| image | 64:10 | 64:6 | 64:3 | 64:1 |")
    print("|---|---|---|---|---|")
    for n, vals in table:
        print(f"| {n} | " + " | ".join(f"{v:.2f}" for v in vals) + " |")
    print("\n## Architecture-level cost (from the RTL structure, not synthesis)\n")
    sch = schedule.build()
    print("| configuration | adders | adder bits | rounding increments | register bits | memory words | "
          "multipliers |")
    print("|---|---|---|---|---|---|---|")
    for mode in cordic2.MODES:
        for w in (10, 14):
            cfg = Config(8, w, 3, (0, 0, 0) if w >= 11 else (1, 1, 1), mode)
            c = cost.processor_cost(cfg, sch)
            print(f"| W={w}, G=3, {mode} | {c.total_adders} | {c.total_adder_bits} | "
                  f"{c.rounding_increments} | {c.total_register_bits} | "
                  f"{sum(c.memory_words.values())} | 0 |")
    u = schedule.utilisation(sch)
    print(f"\nSchedule: period 8, latency {sch.t0 + 1} clocks, banks {sch.nregs}; butterfly unit "
          f"{100 * u['butterfly unit']:.1f} % busy, CORDIC unit {100 * u['CORDIC unit']:.1f} % busy; "
          f"peak ports {schedule.port_usage(sch)}.")

    print("\n## Overflow\n")
    bad = []
    for mode in cordic2.MODES:
        for w in range(8, 17):
            for ss in A.valid_ss(8, w):
                cfg = Config(8, w, 3, ss, mode)
                lo, hi = -(1 << (w - 1)), (1 << (w - 1)) - 1
                nb = A.node_bounds(cfg, n_random=2000)
                pk = A.mr_register_peaks(cfg, n_random=2000)
                if any(a < lo or b > hi for a, b in nb.values()) or any(p > l for p, l in pk.values()):
                    bad.append(cfg.describe())
    print(f"Every valid configuration W = 8..16, every safe-scaling choice, both modes "
          f"({2 * sum(len(A.valid_ss(8, w)) for w in range(8, 17))} configurations): "
          f"{'no overflow in any node or CORDIC register' if not bad else 'OVERFLOW: ' + ', '.join(bad)}.")
    x16 = np.random.default_rng(8).integers(-128, 128, (5000, 16))
    ref = scalable.dct16(x16)
    print("\n## 16-point extension\n")
    print("| engines | rms error | max error |")
    print("|---|---|---|")
    for mode in cordic2.MODES:
        est = scalable.dct16_approx(x16, Config(9, 15, 3, (0, 0, 0), mode))
        e = est - ref
        print(f"| 2 x 8-point W=15 {mode} + Table 5 array | {np.sqrt(np.mean(e ** 2)):.4f} | "
              f"{np.max(np.abs(e)):.3f} |")


if __name__ == "__main__":
    main()
